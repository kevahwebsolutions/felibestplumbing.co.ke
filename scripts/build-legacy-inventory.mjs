import fs from 'node:fs';
import path from 'node:path';
import { LEGACY_ROUTES } from './legacy-map.mjs';

const dir = 'legacy';
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.html'));
const rows = [];
const redirects = [];
const seen = new Set();
const add = (source, destination) => {
  if (source === destination || seen.has(source)) return;
  seen.add(source);
  redirects.push({ source, destination });
};
const encode = (p) => encodeURI(p).replace(/ /g, '%C2%A0');

for (const f of files.sort()) {
  const html = fs.readFileSync(path.join(dir, f), 'utf8');
  const m = html.match(/<title>([^<]*)/i);
  const title = (m ? m[1] : '').trim() || '(empty file)';
  const target = LEGACY_ROUTES[f];
  if (!target) throw new Error('No mapping for ' + f);
  rows.push({ f, title, target });
}
for (const [f, target] of Object.entries(LEGACY_ROUTES)) {
  if (f === '404.html') continue;
  const base = f.replace(/\.html$/, '');
  const variants = new Set([f, f.toLowerCase(), base, base.toLowerCase()]);
  for (const v of variants) {
    add('/' + v, target);
    add('/' + encode(v), target);
    add('/' + v.replace(/ /g, '%20'), target);
    add('/' + v.replace(/ /g, '-'), target);
  }
}
add('/index', '/');
add('/index.html', '/');

let md = '# Legacy inventory and redirect map\n\n';
md += 'Every page of the old static site, its title, the new route and the old-to-new 301. ';
md += 'Generated by `scripts/build-legacy-inventory.mjs` from `scripts/legacy-map.mjs`.\n\n';
md += '| Old file | Old title | New route | Notes |\n|---|---|---|---|\n';
const notes = {
  'header.html': 'Template fragment, no page of its own',
  'product.html': 'Stub 404, replaced by dynamic product pages',
  'shop-item.html': 'Dead template, replaced by /shop/[slug]',
  'single-post.html': 'US HVAC template, replaced by /blog/[slug]',
  'gallery2.html': 'Merged into /gallery',
  'gallery3.html': 'Merged into /gallery',
  'services-item01.html': 'Duplicate of Residential plumbing',
  'services-item02.html': 'Duplicate of Commercial plumbing',
  'services-item03.html': 'Duplicate of Bathroom renovations',
  'Tank Installation and Repair.html': 'Empty duplicate (name has spaces / non-breaking spaces)',
  '404.html': 'Replaced by app/not-found.tsx',
};
for (const r of rows) md += `| \`${r.f}\` | ${r.title.replace(/\|/g, '/')} | \`${r.target}\` | ${notes[r.f] ?? ''} |\n`;
md += `\n## 301 redirects (${redirects.length})\n\nStored in \`config/legacy-redirects.json\` and loaded by \`next.config.mjs\`. Covers capitalised names, names with spaces (plain, %20, hyphenated, non-breaking space), and with or without \`.html\`.\n\n`;
md += '| From | To |\n|---|---|\n';
for (const r of redirects) md += `| \`${r.source}\` | \`${r.destination}\` |\n`;
fs.writeFileSync('docs/legacy-inventory.md', md);
fs.writeFileSync('config/legacy-redirects.json', JSON.stringify(redirects, null, 1));
console.log(rows.length, 'pages', redirects.length, 'redirects');
