// Prints the final JSON-LD of one page of every type into docs/seo-samples.md. Needs a running production build.
// Usage: BASE_URL=http://localhost:3100 node scripts/seo-samples.mjs
import fs from 'node:fs';

const base = process.env.BASE_URL ?? 'http://localhost:3100';
const pages = [
  ['Home', '/'], ['Service page', '/services/drain-lines'], ['Product page', '/shop/milano-modern-shower'], ['Blog post', '/blog/burst-pipe-what-to-do-first'],
  ['Shop index', '/shop'], ['Category page', '/shop/category/showers'], ['Services index', '/services'], ['FAQ page', '/faq'],
];
const out = ['# Structured data samples', '', 'Final JSON-LD as served by the production build (`NEXT_PUBLIC_SITE_URL=https://felibestplumbing.co.ke`). Generated by `scripts/seo-samples.mjs`. Every block parses as JSON; types are checked by `npm run seo:audit`.', ''];
for (const [label, path] of pages) {
  const html = await (await fetch(base + path)).text();
  const blocks = [...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)].map((m) => JSON.parse(m[1].replace(/\u003c/g, '<')));
  out.push(`## ${label}: \`${path}\``, '');
  for (const b of blocks) out.push('```json', JSON.stringify(b, null, 2), '```', '');
}
fs.writeFileSync('docs/seo-samples.md', out.join('\n'));
console.log('docs/seo-samples.md written');
